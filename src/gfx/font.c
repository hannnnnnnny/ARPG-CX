static const uint8_t glyph_times[7] = {0x00,0x00,0x11,0x0A,0x04,0x0A,0x11};

#define CJK_ADVANCE 8   /* 8x8 CJK cells already include a 1 px gap */

static const uint8_t *glyph_for(unsigned c)
{
    if (c == 'x')
        return glyph_times;
    if (c >= 'a' && c <= 'z')
        c -= 'a' - 'A';
    if (c < 32 || c > 95)
        c = '?';
    return glyphs[c - 32];
}

/* Decode one UTF-8 code point and advance; bad bytes come back as '?'. */
static uint32_t utf8_next(const char **ps)
{
    const uint8_t *s = (const uint8_t *)*ps;
    uint32_t cp;
    int extra, i;
    if (s[0] < 0x80) { *ps += 1; return s[0]; }
    if ((s[0] & 0xE0) == 0xC0) { cp = s[0] & 0x1F; extra = 1; }
    else if ((s[0] & 0xF0) == 0xE0) { cp = s[0] & 0x0F; extra = 2; }
    else if ((s[0] & 0xF8) == 0xF0) { cp = s[0] & 0x07; extra = 3; }
    else { *ps += 1; return '?'; }
    for (i = 1; i <= extra; i++) {
        if ((s[i] & 0xC0) != 0x80) { *ps += i; return '?'; }
        cp = (cp << 6) | (s[i] & 0x3F);
    }
    *ps += extra + 1;
    return cp;
}

static int advance(uint32_t cp) { return cp < 0x80 ? FONT_ADVANCE : CJK_ADVANCE; }

static int raw_width(const char *s, int scale)
{
    int w = 0;
    while (*s)
        w += advance(utf8_next(&s));
    return w ? (w - 1) * scale : 0;
}

int font_text_width(const char *s, int scale)
{
    return raw_width(T(s), scale);
}

static void put_ascii(int x, int y, unsigned ch, uint16_t color, int scale)
{
    const uint8_t *g = glyph_for(ch);
    int r, c;
    for (r = 0; r < FONT_H; r++) {
        uint8_t bits = g[r];
        if (!bits)
            continue;
        for (c = 0; c < FONT_W; c++)
            if (bits & (0x10 >> c)) {
                if (scale == 1)
                    gfx_pixel(x + c, y + r, color);
                else
                    gfx_fill_rect(x + c * scale, y + r * scale, scale, scale, color);
            }
    }
}

/* CJK cell: 8 rows, baseline on row 6 like the 5x7 font's last row. */
static void put_cjk(int x, int y, uint32_t cp, uint16_t color, int scale)
{
    const uint8_t *g = cjk_glyph(cp);
    int r, c;
    if (!g) {                                   /* missing glyph: a small box */
        gfx_rect(x, y, 6 * scale, 7 * scale, color);
        return;
    }
    for (r = 0; r < 8; r++)
        for (c = 0; c < 8; c++)
            if (g[r] & (0x80 >> c)) {
                if (scale == 1)
                    gfx_pixel(x + c, y + r, color);
                else
                    gfx_fill_rect(x + c * scale, y + r * scale, scale, scale, color);
            }
}

static int draw_raw(int x, int y, const char *s, uint16_t color, int scale, int max_w)
{
    int start = x;
    while (*s) {
        uint32_t cp = utf8_next(&s);
        int adv = advance(cp) * scale;
        if (max_w > 0 && x - start + adv - scale > max_w)
            break;                              /* clipped to the given width */
        if (cp < 0x80)
            put_ascii(x, y, cp, color, scale);
        else
            put_cjk(x, y, cp, color, scale);
        x += adv;
    }
    return x - start;
}

int font_draw(int x, int y, const char *s, uint16_t color, int scale)
{
    return draw_raw(x, y, T(s), color, scale, 0);
}

int font_draw_fit(int x, int y, const char *s, int max_w, uint16_t color)
{
    return draw_raw(x, y, T(s), color, 1, max_w);
}

void font_draw_shadow(int x, int y, const char *s, uint16_t color, uint16_t shadow, int scale)
{
    font_draw(x + scale, y + scale, s, shadow, scale);
    font_draw(x, y, s, color, scale);
}

void font_draw_centered(int y, const char *s, uint16_t color, uint16_t shadow, int scale)
{
    int x = (SCREEN_W - font_text_width(s, scale)) / 2;
    font_draw_shadow(x, y, s, color, shadow, scale);
}

/* Length in bytes of the next line that fits max_w: breaks at spaces, or
 * between any two CJK characters (they have no spaces). */
static int line_bytes(const char *s, int max_w, int *skip)
{
    const char *p = s, *brk = NULL;
    int w = 0;
    while (*p) {
        const char *at = p;
        uint32_t cp = utf8_next(&p);
        if (cp == ' ')
            brk = at;
        else if (cp >= 0x80 && at != s)
            brk = at;                           /* may break before a CJK char */
        w += advance(cp);
        if (w - 1 > max_w) {
            const char *cut = brk && brk != s ? brk : at;
            if (cut == s)
                cut = p;                        /* one oversized glyph: take it */
            *skip = *cut == ' ' ? 1 : 0;
            return (int)(cut - s);
        }
    }
    *skip = 0;
    return (int)(p - s);
}

int font_draw_wrapped_clip(int x, int y, const char *s, int max_w, uint16_t color, int max_y)
{
    char line[160];
    s = T(s);
    while (*s) {
        int skip, n = line_bytes(s, max_w, &skip);
        if (n >= (int)sizeof line)
            n = (int)sizeof line - 1;
        memcpy(line, s, (size_t)n);
        line[n] = 0;
        if (y + FONT_H <= max_y)
            draw_raw(x, y, line, color, 1, 0);
        y += FONT_H + 3;
        s += n + skip;
        while (*s == ' ')
            s++;
        if (n == 0 && !skip)
            break;                              /* safety: never loop forever */
    }
    return y;
}

int font_draw_wrapped(int x, int y, const char *s, int max_w, uint16_t color)
{
    return font_draw_wrapped_clip(x, y, s, max_w, color, SCREEN_H);
}
